import type { ReportSchedule } from '@/features/reports/db/reports';
import { addDays, toIsoDay } from '@/lib/format';

export const WEEKDAYS = ['Domingo', 'Lunes', 'Martes', 'Miércoles', 'Jueves', 'Viernes', 'Sábado'];

export const FREQUENCIES = {
  daily: { label: 'Diario', hint: 'Cubre ese día (o el anterior si se genera antes del mediodía)' },
  weekly: { label: 'Semanal', hint: 'Cubre los últimos 7 días' },
  monthly: { label: 'Mensual', hint: 'Cubre el mes anterior completo' },
} as const;

type When = Pick<ReportSchedule, 'frequency' | 'weekday' | 'month_day' | 'hour'>;

export function describeSchedule(s: When) {
  const hour = `${String(s.hour).padStart(2, '0')}:00`;
  if (s.frequency === 'daily') return `Todos los días a las ${hour}`;
  if (s.frequency === 'weekly') return `Cada ${WEEKDAYS[s.weekday ?? 0].toLowerCase()} a las ${hour}`;
  return `El día ${s.month_day ?? 1} de cada mes a las ${hour}`;
}

/** The last moment, at or before `now`, when this schedule should have run. */
export function latestRun(s: When, now = new Date()) {
  const at = new Date(now);
  at.setHours(s.hour, 0, 0, 0);
  if (s.frequency === 'daily') {
    if (at > now) at.setDate(at.getDate() - 1);
  } else if (s.frequency === 'weekly') {
    const back = (at.getDay() - (s.weekday ?? 0) + 7) % 7;
    at.setDate(at.getDate() - back);
    if (at > now) at.setDate(at.getDate() - 7);
  } else {
    at.setDate(s.month_day ?? 1);
    if (at > now) at.setMonth(at.getMonth() - 1);
  }
  return at;
}

/**
 * The days a run covers: that day, the 7 days up to it, or the previous calendar month.
 * Morning runs close the day before, since the current day has barely started.
 */
export function periodFor(s: When, runAt: Date) {
  const day = runAt.getHours() < 12 ? addDays(toIsoDay(runAt), -1) : toIsoDay(runAt);
  if (s.frequency === 'daily') return { start: day, end: day };
  if (s.frequency === 'weekly') return { start: addDays(day, -6), end: day };
  const first = new Date(runAt.getFullYear(), runAt.getMonth() - 1, 1);
  const last = new Date(runAt.getFullYear(), runAt.getMonth(), 0);
  return { start: toIsoDay(first), end: toIsoDay(last) };
}

export const periodKey = (p: { start: string; end: string }) => `${p.start}_${p.end}`;

/** Quick periods for reports generated by hand. */
export function quickPeriods(now = new Date()) {
  const today = toIsoDay(now);
  const firstOfMonth = toIsoDay(new Date(now.getFullYear(), now.getMonth(), 1));
  const prevFirst = toIsoDay(new Date(now.getFullYear(), now.getMonth() - 1, 1));
  const prevLast = toIsoDay(new Date(now.getFullYear(), now.getMonth(), 0));
  return [
    { key: 'today', label: 'Hoy', start: today, end: today },
    { key: 'yesterday', label: 'Ayer', start: addDays(today, -1), end: addDays(today, -1) },
    { key: 'week', label: 'Últimos 7 días', start: addDays(today, -6), end: today },
    { key: 'month', label: 'Este mes', start: firstOfMonth, end: today },
    { key: 'prev-month', label: 'Mes anterior', start: prevFirst, end: prevLast },
  ];
}
